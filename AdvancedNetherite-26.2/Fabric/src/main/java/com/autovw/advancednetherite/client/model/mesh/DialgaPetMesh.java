    public static LayerDefinition create()
    {
        MeshDefinition meshDefinition = new MeshDefinition();
        PartDefinition root = meshDefinition.getRoot();

        PartDefinition body = root.addOrReplaceChild("body", bodyCubes(), PartPose.ZERO);
        body.addOrReplaceChild("chest_gem", chestGemCubes(), PartPose.offset(0.1F, -1.1F, -19.1F));
        body.addOrReplaceChild("back_plate", backPlateCubes(), PartPose.offset(0.1F, -8.1F, 2.1F));
        PartDefinition neck = body.addOrReplaceChild("neck", neckCubes(), PartPose.offset(0.05F, -7.0F, -13.1F));
        neck.addOrReplaceChild("head", headCubes(), PartPose.offset(-0.05F, -18.0F, -3.1F));
        body.addOrReplaceChild("front_upper_left", frontUpperLeftCubes(), PartPose.offset(8.1F, 3.0F, -11.1F));
        body.addOrReplaceChild("front_upper_right", frontUpperRightCubes(), PartPose.offset(-8.1F, 3.0F, -11.1F));
        body.addOrReplaceChild("hind_upper_left", hindUpperLeftCubes(), PartPose.offset(8.1F, 3.0F, 11.1F));
        body.addOrReplaceChild("hind_upper_right", hindUpperRightCubes(), PartPose.offset(-8.1F, 3.0F, 11.1F));
        PartDefinition tailBase = body.addOrReplaceChild("tail_base", tailBaseCubes(), PartPose.offset(0.1F, 0.1F, 16.1F));
        PartDefinition tailMid = tailBase.addOrReplaceChild("tail_mid", tailMidCubes(), PartPose.offset(-0.1F, 0.1F, 14.1F));
        tailMid.addOrReplaceChild("tail_tip", tailTipCubes(), PartPose.offset(0.1F, 0.1F, 12.1F));

        return LayerDefinition.create(meshDefinition, 512, 168);
    }

