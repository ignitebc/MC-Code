    public static LayerDefinition create()
    {
        MeshDefinition meshDefinition = new MeshDefinition();
        PartDefinition root = meshDefinition.getRoot();

        PartDefinition kirby = root.addOrReplaceChild("kirby", kirbyCubes(), PartPose.offset(0.0F, 13.0F, 0.0F));
        kirby.addOrReplaceChild("body", bodyCubes(), PartPose.ZERO);
        kirby.addOrReplaceChild("hand_left", handLeftCubes(), PartPose.offsetAndRotation(8.0F, 1.0F, 0.0F, 0.0F, 0.0F, -0.3F));
        kirby.addOrReplaceChild("hand_right", handRightCubes(), PartPose.offsetAndRotation(-8.0F, 1.0F, 0.0F, 0.0F, 0.0F, 0.3F));
        kirby.addOrReplaceChild("foot_left", footLeftCubes(), PartPose.offset(4.2F, 8.5F, -1.0F));
        kirby.addOrReplaceChild("foot_right", footRightCubes(), PartPose.offset(-4.2F, 8.5F, -1.0F));

        return LayerDefinition.create(meshDefinition, 256, 80);
    }

