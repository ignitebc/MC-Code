    public static LayerDefinition create()
    {
        MeshDefinition meshDefinition = new MeshDefinition();
        PartDefinition root = meshDefinition.getRoot();

        PartDefinition body = root.addOrReplaceChild("body", bodyCubes(), PartPose.offset(0.0F, 5.0F, 0.0F));
        PartDefinition neck = body.addOrReplaceChild("neck", neckCubes(), PartPose.offsetAndRotation(0.0F, -5.0F, -15.0F, -0.55F, 0.0F, 0.0F));
        PartDefinition head = neck.addOrReplaceChild("head", headCubes(), PartPose.offsetAndRotation(0.0F, -1.0F, -16.0F, 0.55F, 0.0F, 0.0F));
        head.addOrReplaceChild("jaw", jawCubes(), PartPose.offsetAndRotation(0.0F, 3.0F, -11.0F, 0.25F, 0.0F, 0.0F));
        PartDefinition wingLeft = body.addOrReplaceChild("wing_left", wingLeftCubes(), PartPose.offsetAndRotation(8.0F, -7.0F, -9.0F, 0.0F, 0.0F, -0.4F));
        wingLeft.addOrReplaceChild("wing_left_outer", wingLeftOuterCubes(), PartPose.offsetAndRotation(28.0F, 0.0F, 0.0F, 0.0F, 0.0F, 0.3F));
        PartDefinition wingRight = body.addOrReplaceChild("wing_right", wingRightCubes(), PartPose.offsetAndRotation(-8.0F, -7.0F, -9.0F, 0.0F, 0.0F, 0.4F));
        wingRight.addOrReplaceChild("wing_right_outer", wingRightOuterCubes(), PartPose.offsetAndRotation(-28.0F, 0.0F, 0.0F, 0.0F, 0.0F, -0.3F));
        body.addOrReplaceChild("front_left_leg", frontLeftLegCubes(), PartPose.offset(9.4F, 2.0F, -9.9F));
        body.addOrReplaceChild("front_right_leg", frontRightLegCubes(), PartPose.offset(-9.4F, 2.0F, -9.9F));
        body.addOrReplaceChild("hind_left_leg", hindLeftLegCubes(), PartPose.offset(9.4F, 2.0F, 12.1F));
        body.addOrReplaceChild("hind_right_leg", hindRightLegCubes(), PartPose.offset(-9.4F, 2.0F, 12.1F));
        PartDefinition tail1 = body.addOrReplaceChild("tail_1", tail1Cubes(), PartPose.offset(0.1F, 0.1F, 17.0F));
        PartDefinition tail2 = tail1.addOrReplaceChild("tail_2", tail2Cubes(), PartPose.offset(-0.1F, 0.1F, 15.0F));
        tail2.addOrReplaceChild("tail_3", tail3Cubes(), PartPose.offset(0.1F, 0.1F, 15.0F));

        return LayerDefinition.create(meshDefinition, 512, 192);
    }

