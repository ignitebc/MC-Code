    public static LayerDefinition create()
    {
        MeshDefinition meshDefinition = new MeshDefinition();
        PartDefinition root = meshDefinition.getRoot();

        PartDefinition body = root.addOrReplaceChild("body", bodyCubes(), PartPose.offset(0.0F, 6.0F, 0.0F));
        PartDefinition neck = body.addOrReplaceChild("neck", neckCubes(), PartPose.offsetAndRotation(0.0F, -7.0F, -10.0F, 0.35F, 0.0F, 0.0F));
        PartDefinition head = neck.addOrReplaceChild("head", headCubes(), PartPose.offsetAndRotation(0.0F, -9.0F, -1.0F, -0.35F, 0.0F, 0.0F));
        head.addOrReplaceChild("beak", beakCubes(), PartPose.offset(0.0F, -1.0F, -9.0F));
        body.addOrReplaceChild("left_wing", leftWingCubes(), PartPose.offset(7.5F, -5.1F, -7.1F));
        body.addOrReplaceChild("right_wing", rightWingCubes(), PartPose.offset(-7.5F, -5.1F, -7.1F));
        body.addOrReplaceChild("tail", tailCubes(), PartPose.offsetAndRotation(0.0F, 1.0F, 17.0F, 0.18F, 0.0F, 0.0F));
        body.addOrReplaceChild("left_leg", leftLegCubes(), PartPose.offset(4.1F, 8.0F, 4.1F));
        body.addOrReplaceChild("right_leg", rightLegCubes(), PartPose.offset(-4.1F, 8.0F, 4.1F));

        return LayerDefinition.create(meshDefinition, 512, 144);
    }

